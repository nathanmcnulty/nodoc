import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { buildRefreshInventory } from "./portal-refresh-inventory.mjs";
import { assertPublicCoverageSnapshot, loadPublicCoverageSnapshots } from "./public-coverage.mjs";
import { repoRoot } from "./spec-quality-lib.mjs";

const outputPath = path.join(repoRoot, "src", "generated", "publicCoverage.ts");

async function main() {
  const snapshots = await loadPublicCoverageSnapshots();
  const latest = snapshots.at(-1);
  // Authored gaps come from today's source; observations come only from the
  // reviewed snapshot. Rebuilding the site never renews an observation date.
  const inventory = await buildRefreshInventory({ asOf: latest.snapshotId, freshnessDays: latest.windowDays });
  assertPublicCoverageSnapshot(latest, { knownSpecIds: new Set(inventory.specs.map(spec => spec.specId)) });
  const latestBySpec = new Map(latest.specs.map(({ specId, title, ...row }) => [specId, row]));
  const data = {
    latestSnapshotId: latest.snapshotId,
    snapshots: snapshots.map(({ snapshotId, assessedAt, windowDays, source, totals }) => ({ snapshotId, assessedAt, windowDays, source, totals })).reverse(),
    currentSource: {
      specs: inventory.summary.specCount,
      operations: inventory.summary.operationCount,
      schemaGaps: inventory.summary.schemaGaps,
      exampleGaps: inventory.summary.exampleGaps,
    },
    specs: inventory.specs.map(spec => ({
      specId: spec.specId,
      title: spec.title,
      current: { operations: spec.operationCount, schemaGaps: spec.freshness.schemaGaps, exampleGaps: spec.freshness.exampleGaps },
      latest: latestBySpec.get(spec.specId) ?? null,
    })).sort((a, b) => a.title.localeCompare(b.title)),
  };
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, "// This file is auto-generated by tools/generate-public-coverage.mjs.\n"
    + "// Do not edit by hand. Source snapshots live in src/data/coverageSnapshots.\n\n"
    + `export const publicCoverage = ${JSON.stringify(data, null, 2)} as const;\n`, "utf8");
  console.log(`Generated ${path.relative(repoRoot, outputPath).replaceAll("\\", "/")}`);
}

await main();

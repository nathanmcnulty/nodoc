export const operationIndexPath = path.join(repoRoot, "src", "generated", "operationIndex.json");
export const OPERATION_INDEX_SCHEMA_VERSION = 1;
export const DEFAULT_SITE_URL = "https://nodoc.nathanmcnulty.com";

const httpMethods = ["get", "put", "post", "patch", "delete", "head", "options", "trace"];
const navigationDocumentName = "nodoc";
// Scalar treats these markers as schema sub-anchors; an operation id containing
// one would not resolve to the operation itself.
const schemaParamMarkers = [".body.", ".path.", ".query.", ".header.", ".responses."];

export const operationFields = Object.freeze([
  "specId", "method", "path", "operationId", "summary", "tags", "deprecated", "schemaGap", "exampleGap", "anchor",
]);
export const specificationFields = Object.freeze([
  "specId", "title", "category", "route", "version", "openapiVersion", "operationCount",
]);

let navigationModulePromise;

// Resolve the navigation builder through the renderer's own dependency chain so
// anchors are generated by the exact Scalar version that renders the site.
export function loadScalarNavigation() {
  navigationModulePromise ??= (async () => {
    const reactEntry = require.resolve("@scalar/api-reference-react");
    const referenceEntry = createRequire(reactEntry).resolve("@scalar/api-reference");
    const navigationEntry = createRequire(referenceEntry).resolve("@scalar/workspace-store/navigation");
    const navigation = await import(pathToFileURL(navigationEntry).href);
    if (typeof navigation.createNavigation !== "function" || typeof navigation.getOperationEntries !== "function") {
      throw new Error("The installed Scalar workspace store does not expose the navigation helpers.");
    }
    return navigation;
  })();
  return navigationModulePromise;
}

/**
 * Converts a Scalar navigation id into the hash used by a single-document
 * reference, or null when the browser could not route back to the same id.
 */
export function toSingleDocumentAnchor(id, documentSlug = navigationDocumentName) {
  if (typeof id !== "string" || !id.startsWith(`${documentSlug}/`)) return null;
  const hasTrailingSlash = id.endsWith("/");
  const stripped = id.split("/").filter(Boolean).slice(1).join("/");
  const hashId = hasTrailingSlash && stripped ? `${stripped}/` : stripped;
  if (!hashId || schemaParamMarkers.some(marker => hashId.includes(marker))) return null;
  const url = new URL("http://scratch");
  url.hash = hashId;
  const anchor = url.hash.slice(1);
  let decoded;
  try {
    decoded = decodeURIComponent(anchor);
  } catch {
    return null;
  }
  return `${documentSlug}/${decoded}` === id ? anchor : null;
}

export async function buildOperationAnchors(specification) {
  const { createNavigation, getOperationEntries } = await loadScalarNavigation();
  // Navigation traversal annotates the document, so it must never see the source object.
  const navigation = createNavigation(navigationDocumentName, structuredClone(specification), { operationTitleSource: "summary" });
  const anchors = new Map();
  for (const [key, entries] of getOperationEntries(navigation)) {
    const entry = entries.find(item => item?.type === "operation" && typeof item.id === "string");
    if (entry) anchors.set(key, toSingleDocumentAnchor(entry.id));
  }
  return anchors;
}

function textOrNull(value) {
  return typeof value === "string" && value.trim() ? value.replace(/\s+/gu, " ").trim() : null;
}

export async function buildOperationIndexForSpecification({ specId, specification }) {
  const anchors = await buildOperationAnchors(specification);
  const operations = [];
  for (const [operationPath, pathItem] of Object.entries(specification.paths ?? {})) {
    for (const method of httpMethods) {
      const operation = pathItem?.[method];
      if (!operation || typeof operation !== "object") continue;
      const gaps = authoredGaps(operation);
      operations.push({
        specId,
        method: method.toUpperCase(),
        path: operationPath,
        operationId: textOrNull(operation.operationId),
        summary: textOrNull(operation.summary),
        tags: Array.isArray(operation.tags) ? operation.tags.filter(tag => typeof tag === "string") : [],
        deprecated: operation.deprecated === true,
        schemaGap: gaps.schema.length > 0,
        exampleGap: gaps.examples.length > 0,
        anchor: anchors.get(`${operationPath}|${method}`) ?? null,
      });
    }
  }
  return operations.sort((left, right) => left.path.localeCompare(right.path) || left.method.localeCompare(right.method));
}

export async function loadSiteSpecifications() {
  const inventory = await buildSpecInventory();
  const specifications = [];
  for (const entry of inventory) {
    const specification = await loadBundledSpecification(path.resolve(repoRoot, entry.specPath));
    specifications.push({ ...entry, specification });
  }
  return specifications;
}

export async function buildOperationIndex(specifications) {
  const specs = [];
  const operations = [];
  for (const { specId, title, specification } of specifications) {
    const specOperations = await buildOperationIndexForSpecification({ specId, specification });
    specs.push({
      specId,
      title,
      category: textOrNull(specification.info?.["x-nodoc-category"]),
      route: getSpecificationRoute(specification, "/"),
      version: textOrNull(specification.info?.version),
      openapiVersion: textOrNull(specification.openapi),
      operationCount: specOperations.length,
    });
    operations.push(...specOperations);
  }
  return {
    schemaVersion: OPERATION_INDEX_SCHEMA_VERSION,
    source: "specifications/*/specification/openapi.yml",
    note: "Authored specification structure only. Gap flags describe the checked-in documents, not observed portal behavior.",
    specs,
    operations,
  };
}

// One operation per line keeps monthly diffs reviewable without a large file.
export function serializeOperationIndex(index) {
  const header = Object.fromEntries(Object.entries(index).filter(([key]) => key !== "operations"));
  const headerLines = JSON.stringify(header, null, 2).split("\n");
  const operationLines = index.operations.map(operation => `    ${JSON.stringify(operation)}`);
  const body = operationLines.length ? `[\n${operationLines.join(",\n")}\n  ]` : "[]";
  return `${headerLines.slice(0, -1).join("\n")},\n  "operations": ${body}\n}\n`;
}

function absoluteUrl(siteUrl, baseUrl, route) {
  const pathname = path.posix.join("/", baseUrl || "/", route || "/");
  return `${siteUrl.replace(/\/+$/u, "")}${pathname === "/" ? "/" : pathname.replace(/\/+$/u, "")}`;
}

export function serializeOpenApiDocument(specification) {
  return `${JSON.stringify(specification, null, 2)}\n`;
}

export function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

export function buildSiteArtifacts({ specifications, operationIndex, siteUrl = DEFAULT_SITE_URL, baseUrl = "/" }) {
  const files = new Map();
  const specById = new Map(operationIndex.specs.map(spec => [spec.specId, spec]));
  const catalogEntries = [];
  for (const { specId, specification } of specifications) {
    const indexed = specById.get(specId);
    if (!indexed) throw new Error(`Operation index is missing ${specId}.`);
    const text = serializeOpenApiDocument(specification);
    const relativePath = `openapi/${specId}.json`;
    files.set(relativePath, text);
    catalogEntries.push({
      specId,
      title: indexed.title,
      category: indexed.category,
      page: absoluteUrl(siteUrl, baseUrl, indexed.route),
      openapi: absoluteUrl(siteUrl, baseUrl, relativePath),
      openapiVersion: indexed.openapiVersion,
      version: indexed.version,
      operationCount: indexed.operationCount,
      bytes: Buffer.byteLength(text, "utf8"),
      sha256: sha256(text),
    });
  }

  const catalog = {
    schemaVersion: OPERATION_INDEX_SCHEMA_VERSION,
    site: absoluteUrl(siteUrl, baseUrl, "/"),
    note: "Community-authored OpenAPI documents for undocumented Microsoft portal APIs. They describe observed or inferred interfaces and are not supported by Microsoft.",
    specifications: catalogEntries,
  };
  files.set("openapi/index.json", `${JSON.stringify(catalog, null, 2)}\n`);

  const operations = {
    schemaVersion: OPERATION_INDEX_SCHEMA_VERSION,
    site: catalog.site,
    note: operationIndex.note,
    specifications: catalogEntries.map(({ specId, title, category, page, openapi, operationCount }) => ({ specId, title, category, page, openapi, operationCount })),
    operations: operationIndex.operations.map(operation => {
      const page = catalogEntries.find(entry => entry.specId === operation.specId).page;
      return { ...operation, href: operation.anchor ? `${page}#${operation.anchor}` : page };
    }),
  };
  files.set("operations.json", serializeOperationIndex(operations));
  files.set("llms.txt", buildLlmsText({ catalog, operationCount: operationIndex.operations.length, siteUrl, baseUrl }));
  return { files, catalog };
}

export function buildLlmsText({ catalog, operationCount, siteUrl = DEFAULT_SITE_URL, baseUrl = "/" }) {
  const lines = [
    "# nodoc",
    "",
    "> Community-authored OpenAPI specifications for undocumented Microsoft portal APIs, published for building CLIs, browser extensions, and automation around tasks the portals do not expose natively.",
    "",
    "These documents are not supported by Microsoft. Interfaces can change without notice, and authored schemas or examples may be incomplete. Treat every request as acting with the signed-in user's permissions.",
    "",
    `The catalog currently lists ${catalog.specifications.length} specifications and ${operationCount} operations.`,
    "",
    "## Machine-readable indexes",
    "",
    `- [OpenAPI catalog](${absoluteUrl(siteUrl, baseUrl, "openapi/index.json")}): every specification with its page, OpenAPI JSON download, operation count, size, and SHA-256 digest.`,
    `- [Operation index](${absoluteUrl(siteUrl, baseUrl, "operations.json")}): every operation with method, path, summary, tags, authored gap flags, and a deep link.`,
    `- [Operation search](${absoluteUrl(siteUrl, baseUrl, "operations")}): searchable operation list for people.`,
    `- [Coverage](${absoluteUrl(siteUrl, baseUrl, "coverage")}): reviewed observation snapshots and authored gap counts.`,
    "",
    "## Specifications",
    "",
    ...catalog.specifications.map(entry => `- [${entry.title}](${entry.page}): ${entry.operationCount} operations. OpenAPI JSON: ${entry.openapi}`),
    "",
  ];
  return lines.join("\n");
}

export function assertOperationIndexShape(index) {
  if (index?.schemaVersion !== OPERATION_INDEX_SCHEMA_VERSION) throw new Error("Unsupported operation index schema version.");
  if (!Array.isArray(index.specs) || !Array.isArray(index.operations)) throw new Error("Operation index must list specs and operations.");
  const specIds = new Set();
  for (const spec of index.specs) {
    const keys = Object.keys(spec);
    if (keys.join(",") !== specificationFields.join(",")) throw new Error(`Unexpected specification fields for ${spec.specId}: ${keys.join(", ")}`);
    if (specIds.has(spec.specId)) throw new Error(`Duplicate specification ${spec.specId}.`);
    specIds.add(spec.specId);
  }
  const keysSeen = new Set();
  const counts = new Map();
  for (const operation of index.operations) {
    const keys = Object.keys(operation);
    if (keys.join(",") !== operationFields.join(",")) throw new Error(`Unexpected operation fields: ${keys.join(", ")}`);
    if (!specIds.has(operation.specId)) throw new Error(`Operation references unknown specification ${operation.specId}.`);
    const key = `${operation.specId} ${operation.method} ${operation.path}`;
    if (keysSeen.has(key)) throw new Error(`Duplicate operation ${key}.`);
    keysSeen.add(key);
    counts.set(operation.specId, (counts.get(operation.specId) ?? 0) + 1);
  }
  for (const spec of index.specs) {
    if ((counts.get(spec.specId) ?? 0) !== spec.operationCount) throw new Error(`Operation count mismatch for ${spec.specId}.`);
  }
  return true;
}
